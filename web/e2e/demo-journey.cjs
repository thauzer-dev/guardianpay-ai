// Jornada E2E (Playwright): cenários A (prevenção) e B (colaboração) na interface real. Servidor: GP_DEMO_MODE=1, host local.
const { chromium } = require('playwright');
const OUT = process.env.OUT || 'docs/screenshots/';
const BASE = process.env.BASE || 'http://127.0.0.1:8000/';
(async () => {
  const browser = await chromium.launch();
  const page = await browser.newPage({ viewport: { width: 1440, height: 900 }, deviceScaleFactor: 2 });
  page.on('pageerror', (e) => console.log('PAGEERROR', e.message));
  const shot = async (n) => { await page.waitForTimeout(600); await page.screenshot({ path: OUT + n + '.png' }); console.log('shot', n); };
  const nav = async (label) => page.getByRole('button', { name: label, exact: true }).first().click();
  await page.goto(BASE, { waitUntil: 'networkidle' });
  await page.getByRole('checkbox').uncheck();                       // aprovação humana pela interface (sem simulador)
  await page.locator('input').first().fill('Demonstração jurados');
  await page.getByRole('button', { name: /Nova instância/ }).click();
  await page.getByText('Modo demonstração.').waitFor();
  await shot('01-login-demo');
  await page.getByRole('button', { name: /Larissa Gomes/ }).click();
  await nav('Jornada guiada');
  await page.getByText('0/10 etapas').waitFor();
  await page.getByRole('button', { name: /Executar 1 passo do agente/ }).click();
  await page.getByText(/[6-9]\/10 etapas/).waitFor({ timeout: 60000 });
  await shot('02-jornada-apos-deteccao');
  await nav('Centro de Operações');
  await page.getByText('Próximo corte bancário').waitFor();
  await shot('03-centro-operacoes');
  await page.goto(page.url().replace(/\/overview.*$/, '/cases/R5-TP431754'));
  await page.getByText('Evidências por fonte').waitFor();
  await shot('04-caso-R5-boleto-falso');
  await nav('Agente');
  await page.getByRole('button', { name: 'por que o TP431754 foi bloqueado?' }).click();
  await page.getByText(/Contradição: Boleto no ERP/).waitFor();
  await page.getByRole('button', { name: 'investigue a NF 11094' }).click();
  await page.getByText(/Qual título\?/).waitFor();
  await page.getByRole('button', { name: /^1\) TP/ }).click();
  await page.getByText(/retomada do esclarecimento/).first().waitFor({ state: 'attached' });
  await shot('05-agente-linguagem-natural');
  await nav('Jornada guiada');
  await page.getByRole('button', { name: /Entrar como usuario_12/ }).click();
  await page.getByRole('button', { name: 'Abrir caixa de aprovações' }).click();
  const card = page.locator('section', { hasText: 'TP431459' }).filter({ hasText: 'Corrigir lançamento' }).first();
  await card.waitFor();
  await card.getByPlaceholder(/Comentário/).fill('Valor conferido com a duplicata do XML');
  await card.getByRole('button', { name: /Aprovar/ }).click();
  await page.getByText(/registrada: ok/).waitFor({ timeout: 30000 });
  await page.evaluate(() => window.scrollTo(0, 0));
  await shot('06-aprovacao-humana');
  await nav('Jornada guiada');
  await page.getByRole('button', { name: /Avançar até o corte/ }).click();
  await page.getByText('10/10 etapas').waitFor({ timeout: 60000 });
  await shot('07-jornada-completa');
  await page.goto(page.url().replace(/\/journey.*$/, '/cases/R2-TP431459'));
  await page.getByText('Histórico da investigação').waitFor();
  await page.mouse.wheel(0, 500);
  await shot('08-caso-R2-retomado');
  await page.setViewportSize({ width: 390, height: 844 });
  await nav('Jornada guiada');
  await shot('09-mobile-jornada');
  await browser.close();
})().catch((e) => { console.error('E2E FAIL', e.message); process.exit(1); });
